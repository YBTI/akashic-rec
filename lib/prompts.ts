export function articlePrompt(title: string, target: Target, transcript: string) {
  return `以下は「Akashic REC」で行ったインタビューの記録です。自分を救ってくれた存在(対象)との経験を証として語ったこの記録を、インタビュー形式の読み物記事に整えてください。
条件:
- 回答者が語った事実と言葉を尊重し、語られていない出来事・数字・人物を創作しない。
- 話し言葉は読みやすく整えるが、語り手の口調と気持ちは残す。重複や脱線は省いてよい。
- 質問は記事として自然な文に整える。似た質問はまとめてよい。
- 語り手の信仰や対象への敬意を尊重する。
- 記事の題名は人名ではないので、本文で題名を人物のように扱わない。${targetNote(target)}
- 自然で正しい日本語で書く。
- lead は記事冒頭の導入文(2〜3文)。blocks は質問(q)と回答(a)の組。

記事の題名:「${title}」
対象:${target}
記録:
${transcript}`;
}
